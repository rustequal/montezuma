; OB_FRAME gets address+2, that is, the header is stepped over
; (see VIDINI: mov ax,[ANIMTB..]; add ax,2).
; Transparency goes through MSKTAB, granular to a nibble = 2 pixels.
;-----------------------------------------------------------------------
